import React, { useState } from 'react';
import type { AnalysisResult } from '../types';
import { Copy, Check, Download, FileText, Code2, Maximize2, Minimize2 } from 'lucide-react';

interface JsonViewerProps {
  data: AnalysisResult;
}

export const JsonViewer: React.FC<JsonViewerProps> = ({ data }) => {
  const [copied, setCopied] = useState(false);
  const [isExpanded, setIsExpanded] = useState(false);

  const jsonString = JSON.stringify(data, null, 2);

  const handleCopyJson = () => {
    navigator.clipboard.writeText(jsonString);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadJson = () => {
    const blob = new Blob([jsonString], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${data.metadata.filename.replace(/\.css$/i, '')}_analysis.json`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const generateMarkdownReport = (): string => {
    const meta = data.metadata;
    return `# CSS INSIGHT — Telemetry Analysis Report

**File:** \`${meta.filename}\`  
**Size:** ${(meta.file_size_bytes / 1024).toFixed(2)} KB  
**Parse Time:** ${meta.parse_time_ms} ms  
**Engine:** \`tinycss2\` AST Engine  

---

## 1. Executive Summary

| Metric | Count |
|---|---|
| Total Style Rules | ${meta.total_rules} |
| Total Individual Selectors | ${meta.total_selectors} |
| Total Declarations | ${meta.total_declarations} |
| Unique CSS Properties | ${meta.unique_properties} |
| Detected Unique Colors | ${meta.unique_colors} |
| Total @rules / Media Queries | ${meta.total_at_rules} |
| Total Comments Parsed | ${meta.total_comments} |
| Diagnostics / Warnings | ${data.warnings.length} |

---

## 2. Top Properties Breakdown

${data.top_properties.map(p => `- **\`${p.property}\`**: ${p.count} times (${p.percentage}%)`).join('\n')}

---

## 3. Detected Colors

${data.detected_colors.map(c => `- \`${c}\``).join('\n')}

---

## 4. Diagnostics & Warnings

${data.warnings.length === 0 ? '_No warnings or duplicate declarations detected._' : data.warnings.map(w => `- [${w.type}] ${w.message} (Line: ${w.line || 'N/A'})`).join('\n')}

---
*Generated by CSS INSIGHT — Milestone 1: CSS Parser*
`;
  };

  const handleDownloadReport = () => {
    const reportText = generateMarkdownReport();
    const blob = new Blob([reportText], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${data.metadata.filename.replace(/\.css$/i, '')}_report.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="rounded-2xl border border-white/[0.08] bg-[#0c1222]/90 shadow-xl overflow-hidden">
      {/* Top action bar */}
      <div className="p-4 sm:p-6 border-b border-white/[0.06] bg-white/[0.01] flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h3 className="text-lg font-bold text-white flex items-center gap-2">
            <Code2 className="h-5 w-5 text-cyan-400" />
            Structured AST JSON Output
          </h3>
          <p className="text-xs text-slate-400 mt-0.5">
            Verified JSON output schema ready for export, CI/CD linting, or telemetry pipelines.
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <button
            onClick={handleCopyJson}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-white/[0.04] hover:bg-white/[0.08] text-slate-200 border border-white/[0.08] transition-all"
          >
            {copied ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
            {copied ? 'Copied to Clipboard!' : 'Copy JSON'}
          </button>

          <button
            onClick={handleDownloadJson}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-cyan-500/10 hover:bg-cyan-500/20 text-cyan-300 border border-cyan-500/30 transition-all"
          >
            <Download className="h-3.5 w-3.5" />
            Download JSON
          </button>

          <button
            onClick={handleDownloadReport}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-violet-500/10 hover:bg-violet-500/20 text-violet-300 border border-violet-500/30 transition-all"
          >
            <FileText className="h-3.5 w-3.5" />
            Download Report (MD)
          </button>

          <button
            onClick={() => setIsExpanded(!isExpanded)}
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-white/[0.04] border border-transparent hover:border-white/[0.08] transition-colors"
            title={isExpanded ? 'Collapse viewer' : 'Expand viewer'}
          >
            {isExpanded ? <Minimize2 className="h-4 w-4" /> : <Maximize2 className="h-4 w-4" />}
          </button>
        </div>
      </div>

      {/* Code Viewer Container */}
      <div className={`p-4 sm:p-6 bg-[#090d16] font-mono text-xs overflow-auto transition-all ${
        isExpanded ? 'max-h-[800px]' : 'max-h-[450px]'
      }`}>
        <pre className="text-slate-300 leading-relaxed">
          <code>{jsonString}</code>
        </pre>
      </div>
    </div>
  );
};
